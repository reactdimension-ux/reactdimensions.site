// the current one. `prefixes` and `suffixes` give each card its unit.
export default function DoodleKpiTiles({
  data = 'Revenue:48200|41800, Active users:12840|13120, Conversion:3.8|3.1, Avg. response:182|240',
  prefixes = '$, , , ',
  suffixes = ', , %, ms',
  invert = 'Avg. response',
  title = 'This month',
  subtitle = 'Compared with last month',
  columns = 4,
  sparkline = 'area',
  points = 20,
  countUp = true,
  compact = true,
  showPrevious = true,
  roughness = 1.2,
  bowing = 1,
  fillStyle = 'hachure',
  hachureGap = 5,
  hachureAngle = -41,
  strokeWidth = 1.8,
  doubleStroke = true,
  boil = false,
  drawOn = true,
  duration = 1800,
  seed = 7,
  paper = 'grid',
  tilt = -0.3,
  width = 760,
  size = 15,
  font = HAND,
  color = '#2e86ab',
  upColor = '#3bb273',
  downColor = '#e4572e',
  cardColor = '#fffefa',
  paperColor = '#fbf8f1',
  inkColor = '#2b2b2b',
  mutedInk = '#77736b',
}) {
  const uid = useId().replace(/:/g, '')
  const [boxRef, boxW] = useWidth()
  const tb = useBoil(boil)
  const sd = seed * 53 + tb * 13
  const o = { roughness, bowing, fillStyle, hachureGap, hachureAngle, strokeWidth, doubleStroke }
  const pre = String(prefixes).split(',').map((s) => s.trim())
  const suf = String(suffixes).split(',').map((s) => s.trim())
  const inv = new Set(splitNames(invert))
  const tiles = useMemo(() => parseRows(data).map((r, i) => {
    const v = r.values[0] ?? 0
    const prev = r.values[1] ?? v
    // a seeded walk from prev to v
    let s = Math.round(seed) * 131 + i * 977 + 1
    const rnd = () => ((s = (s * 9301 + 49297) % 233280) / 233280)
    const n = clamp(Math.round(points), 4, 80)
    const spread = Math.abs(v - prev) * 0.35 + Math.abs(v) * 0.03
    const line = Array.from({ length: n }, (_, k) => { const t = k / (n - 1); return prev + (v - prev) * t + (k && k < n - 1 ? (rnd() - 0.5) * spread : 0) })
    return { label: r.label, v, prev, line, dec: Math.abs(v) < 100 && v % 1 !== 0 ? 1 : 0 }
  }), [data, points, seed])
  const p = useReveal(drawOn, duration, data)
  const [hov, setHov] = useState(-1)
  // boxW is measured on the grid itself, so it is already the inner width
  const W = Math.max(220, boxW || width - size * 2.8)
  // as many columns as fit, preferring a count that leaves no card alone on the last row
  const cap = clamp(Math.min(Math.round(columns), Math.max(1, Math.floor(W / 150))), 1, 6)
  let C = cap
  for (let c = cap; c >= Math.max(1, cap - 2); c--) if (tiles.length <= c || tiles.length % c === 0) { C = c; break }
  const gapPx = size * 1.1
  const tw = Math.max(120, (W - (C - 1) * gapPx) / C)
  // narrow cards put "from …" on its own line under the change
  const stackPrev = showPrevious && tw < size * 14
  const th = size * ((sparkline !== 'none' ? 10.6 : 7.6) + (stackPrev ? 1.1 : 0))
  const draw = (k) => ({ pathLength: 1, strokeDasharray: 1, strokeDashoffset: 1 - k })

  const show = (t, i, x) => {
    const nf = compact && Math.abs(x) >= 10000 ? new Intl.NumberFormat('en', { notation: 'compact', maximumFractionDigits: 1 }) : new Intl.NumberFormat('en', { minimumFractionDigits: t.dec, maximumFractionDigits: t.dec })
    return `${pre[i] ?? ''}${nf.format(x)}${suf[i] ?? ''}`
  }

  return (
    <Paper {...{ width, paper, paperColor, inkColor, mutedInk, size, font, tilt, title, subtitle, accent: color }}>
      <div ref={boxRef} role="list" style={{ display: 'grid', gridTemplateColumns: `repeat(${C}, minmax(0, 1fr))`, gap: gapPx, padding: '0.3em 0 0.2em' }}>
        {tiles.map((t, i) => {
          const ch = t.prev ? (t.v - t.prev) / Math.abs(t.prev) : 0
          const good = inv.has(t.label) ? ch <= 0 : ch >= 0
          const c = good ? upColor : downColor
          const ip = ease(clamp((p - i * 0.08) / 0.75, 0, 1))
          const shown = countUp ? t.prev + (t.v - t.prev) * ip : t.v
          const rot = (srng(seed * 7 + i)() - 0.5) * 2.6
          const lift = hov === i
          const sk = sd + i * 41
          // sparkline geometry
          const sw = tw - size * 1.8
          const sh = size * 2.4
          const lo = Math.min(...t.line)
          const hi = Math.max(...t.line)
          const P = t.line.map((y, k) => [(k / (t.line.length - 1)) * sw, sh - 3 - ((y - lo) / (hi - lo || 1)) * (sh - 6)])
          const area = `M0,${sh}L${P.map((q) => q.map(f1).join(',')).join('L')}L${sw},${sh}Z`
          const up = ch >= 0
          const label = `${t.label}: ${show(t, i, t.v)}, ${up ? 'up' : 'down'} ${Math.abs(ch * 100).toFixed(1)}% from ${show(t, i, t.prev)}`
          return (
            <div
              key={i}
              role="listitem"
              aria-label={label}
              onMouseEnter={() => setHov(i)}
              onMouseLeave={() => setHov(-1)}
              style={{
                position: 'relative',
                height: th,
                boxSizing: 'border-box',
                padding: `${size * 0.75}px ${size * 0.9}px`,
                // an index card: one red header rule, faint blue rules below
                background: `linear-gradient(${downColor}55, ${downColor}55) 0 ${size * 2.35}px / 100% 1.5px no-repeat, repeating-linear-gradient(transparent 0 ${size * 1.6 - 1}px, ${color}22 ${size * 1.6 - 1}px ${size * 1.6}px) 0 ${size * 2.35}px / 100% 100% no-repeat, ${cardColor}`,
                boxShadow: lift ? '3px 10px 18px -8px #00000059' : '1px 4px 10px -5px #00000040',
                opacity: 0.25 + 0.75 * ip,
                transform: `translateY(${(1 - ip) * 10 - (lift ? 3 : 0)}px) rotate(${lift ? 0 : rot}deg)`,
                transition: 'transform .25s, box-shadow .25s',
              }}
            >
              {/* a strip of tape holding the card down */}
              <span style={{ position: 'absolute', top: -7, left: '50%', width: 44, height: 13, transform: `translateX(-50%) rotate(${-rot * 1.5}deg)`, background: '#ffffffa6', boxShadow: '0 0 0 1px #0000000d' }} />
              {/* pen outline of the card */}
              <svg width={tw} height={th} viewBox={`0 0 ${tw} ${th}`} aria-hidden style={{ position: 'absolute', inset: 0, overflow: 'visible', pointerEvents: 'none' }}>
                <path d={sketchRect(sk, 1, 1, tw - 2, th - 2, { ...o, roughness: roughness * 0.5, doubleStroke: false })} fill="none" stroke={inkColor} strokeOpacity={lift ? 0.9 : 0.55} strokeWidth={lift ? strokeWidth : strokeWidth * 0.7} strokeLinejoin="round" {...draw(ip)} />
              </svg>
              <div style={{ position: 'relative', color: mutedInk, fontSize: '1.05em', whiteSpace: 'nowrap', overflow: 'hidden', textOverflow: 'ellipsis' }}>{t.label}</div>
              <div style={{ position: 'relative', fontSize: '2.15em', fontWeight: 700, lineHeight: 1.1, margin: '0.12em 0 0.05em', fontVariantNumeric: 'tabular-nums', whiteSpace: 'nowrap' }}>{show(t, i, shown)}</div>
              <div style={{ position: 'relative', display: 'flex', alignItems: 'center', gap: '0.35em', flexWrap: 'nowrap', whiteSpace: 'nowrap', overflow: 'hidden' }}>
                <svg width={size * 1.7} height={size * 1.4} viewBox="0 0 26 22" aria-hidden style={{ flex: 'none', overflow: 'visible' }}>
                  <path d={up ? arrowD(sk + 3, 3, 19, 22, 4, { ...o, roughness: roughness * 0.6 }, 0.25) : arrowD(sk + 3, 3, 3, 22, 18, { ...o, roughness: roughness * 0.6 }, -0.25)} fill="none" stroke={c} strokeWidth={strokeWidth * 1.15} strokeLinecap="round" strokeLinejoin="round" {...draw(ease(clamp((ip - 0.3) / 0.7, 0, 1)))} />
                </svg>
                <b style={{ color: c, fontSize: '1.1em', fontVariantNumeric: 'tabular-nums' }}>{`${up ? '+' : '−'}${Math.abs(ch * 100).toFixed(1)}%`}</b>
                {showPrevious && !stackPrev && <span style={{ color: mutedInk, overflow: 'hidden', textOverflow: 'ellipsis' }}>{`from ${show(t, i, t.prev)}`}</span>}
              </div>
              {showPrevious && stackPrev && <div style={{ position: 'relative', color: mutedInk, fontSize: '0.92em', whiteSpace: 'nowrap', overflow: 'hidden', textOverflow: 'ellipsis' }}>{`from ${show(t, i, t.prev)}`}</div>}
              {sparkline !== 'none' && (
                <svg width={sw} height={sh} viewBox={`0 0 ${sw} ${sh}`} aria-hidden style={{ position: 'absolute', left: size * 0.9, bottom: size * 0.7, overflow: 'visible' }}>
                  {sparkline === 'area' && <SketchFill id={`${uid}a${i}`} clip={area} box={{ x: 0, y: 0, w: sw, h: sh }} color={c} o={{ ...o, hachureGap: Math.max(3, hachureGap) }} seed={sk + 9} prog={ip} opacity={0.4} />}
                  <path d={sketchCurve(sk + 11, P, { ...o, roughness: roughness * 0.45 })} fill="none" stroke={c} strokeWidth={strokeWidth * 0.95} strokeLinecap="round" strokeLinejoin="round" {...draw(ip)} />
                  {ip > 0.95 && <path d={sketchEllipse(sk + 13, P[P.length - 1][0], P[P.length - 1][1], 3.2, 3.2, { ...o, doubleStroke: false })} fill={cardColor} stroke={c} strokeWidth={strokeWidth * 0.9} />}
                </svg>
              )}
            </div>
          )
        })}
      </div>
    </Paper>
  )
}
