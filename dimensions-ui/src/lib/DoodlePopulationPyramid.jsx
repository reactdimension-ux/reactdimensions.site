// and hover a band to compare both sides on a sticky note.
export default function DoodlePopulationPyramid({
  data = '85+:1.1|2.0, 75-84:3.0|3.8, 65-74:5.2|5.8, 55-64:6.4|6.7, 45-54:6.6|6.6, 35-44:6.8|6.7, 25-34:7.0|6.8, 15-24:6.1|5.8, 5-14:5.6|5.3, 0-4:2.6|2.5',
  leftLabel = 'Male',
  rightLabel = 'Female',
  title = 'Population by age',
  subtitle = 'Millions of people',
  normalize = false,
  centerLabels = true,
  gap = 0.18,
  showValues = true,
  showGrid = true,
  roughness = 1.2,
  bowing = 1,
  fillStyle = 'hachure',
  hachureGap = 5,
  hachureAngle = -41,
  strokeWidth = 1.8,
  doubleStroke = true,
  boil = false,
  drawOn = true,
  duration = 2000,
  seed = 5,
  tooltip = true,
  decimals = 1,
  prefix = '',
  suffix = 'M',
  paper = 'grid',
  tilt = -0.5,
  width = 640,
  height = 300,
  size = 15,
  font = HAND,
  leftColor = '#2e86ab',
  rightColor = '#e4572e',
  paperColor = '#fbf8f1',
  inkColor = '#2b2b2b',
  mutedInk = '#77736b',
}) {
  const uid = useId().replace(/:/g, '')
  const wrap = useRef(null)
  const [boxRef, boxW] = useWidth()
  const t = useBoil(boil)
  const sd = seed * 67 + t * 13
  const o = { roughness, bowing, fillStyle, hachureGap, hachureAngle, strokeWidth, doubleStroke }
  const rows = useMemo(() => parseRows(data).map((r) => ({ label: r.label, a: Math.max(0, r.values[0] ?? 0), b: Math.max(0, r.values[1] ?? 0) })), [data])
  const sumA = rows.reduce((s, r) => s + r.a, 0) || 1
  const sumB = rows.reduce((s, r) => s + r.b, 0) || 1
  const valA = (r) => (normalize ? (r.a / sumA) * 100 : r.a)
  const valB = (r) => (normalize ? (r.b / sumB) * 100 : r.b)
  const fmt = normalize ? (v) => `${v.toFixed(1)}%` : makeFmt({ decimals, prefix, suffix })
  const n = rows.length
  const p = useReveal(drawOn, duration, `${data}|${normalize}`)
  const [hov, setHov] = useState(-1)
  const [tip, setTip] = useState(null)

  const W = Math.max(280, (boxW || width) - size * 2.8)
  const H = height
  const maxLab = Math.max(...rows.map((r) => r.label.length))
  const mid = centerLabels ? maxLab * size * 0.52 + 22 : 6
  const m = { l: centerLabels ? 6 : maxLab * size * 0.52 + 16, r: 6, t: size * 1.9, b: size * 1.8 }
  const half = (W - m.l - m.r - mid) / 2
  const cx = m.l + half + mid / 2
  const ph = H - m.t - m.b
  const band = ph / Math.max(1, n)
  const bh = band * (1 - clamp(gap, 0.02, 0.7))
  const top = niceRange(0, Math.max(...rows.map((r) => Math.max(valA(r), valB(r)))), 3)
  const len = (v) => (v / top.hi) * (half - (showValues ? size * 2.8 : 6))
  const axisP = ease(clamp(p / 0.22, 0, 1))
  const draw = (k) => ({ pathLength: 1, strokeDasharray: 1, strokeDashoffset: 1 - k })
  const xl = cx - mid / 2
  const xr = cx + mid / 2
  const angL = hachureAngle
  const angR = 180 - hachureAngle

  return (
    <Paper wrapRef={(el) => { wrap.current = el; boxRef.current = el }} {...{ width, paper, paperColor, inkColor, mutedInk, size, font, tilt, title, subtitle, tip, accent: rightColor }}>
      <svg width={W} height={H} viewBox={`0 0 ${W} ${H}`} role="img" aria-label={`${title}. Hand-drawn population pyramid, ${leftLabel} and ${rightLabel}. ${rows.map((r) => `${r.label}: ${fmt(valA(r))} and ${fmt(valB(r))}`).join('; ')}`} style={{ display: 'block', maxWidth: '100%', overflow: 'visible' }} onMouseLeave={() => { setHov(-1); setTip(null) }}>
        {/* side headings with little pen arrows */}
        <g opacity={axisP}>
          <text x={xl - size * 2.4} y={size * 0.95} textAnchor="end" fontSize={size * 1.15} fontWeight="700" fill={leftColor}>{leftLabel}</text>
          <path d={arrowD(sd + 1, xl - size * 0.4, size * 0.6, xl - size * 2, size * 0.6, { ...o, doubleStroke: false }, 0.12)} fill="none" stroke={leftColor} strokeWidth={strokeWidth * 0.85} strokeLinecap="round" />
          <text x={xr + size * 2.4} y={size * 0.95} fontSize={size * 1.15} fontWeight="700" fill={rightColor}>{rightLabel}</text>
          <path d={arrowD(sd + 2, xr + size * 0.4, size * 0.6, xr + size * 2, size * 0.6, { ...o, doubleStroke: false }, -0.12)} fill="none" stroke={rightColor} strokeWidth={strokeWidth * 0.85} strokeLinecap="round" />
        </g>

        {/* pencil grid and scale */}
        {ticksOf(top).map((v, i) => [-1, 1].map((s) => {
          const x = s < 0 ? xl - len(v) : xr + len(v)
          return (
            <g key={`${i}${s}`} style={{ pointerEvents: 'none' }}>
              {showGrid && v > 0 && <path d={sketchLine(sd + i * 3 + (s > 0 ? 40 : 0), x, m.t + 2, x, m.t + ph - 2, { ...o, doubleStroke: false, roughness: roughness * 0.5 })} fill="none" stroke={inkColor} strokeOpacity="0.15" strokeWidth="1" {...draw(axisP)} />}
              {!(v === 0 && s > 0 && mid < size * 2) && <text x={x} y={H - 3} textAnchor="middle" fontSize={size * 0.85} fill={mutedInk} opacity={axisP}>{normalize ? `${v}%` : axisFmt.format(v)}</text>}
            </g>
          )
        }))}
        <path d={sketchLine(sd + 60, xl, m.t - 4, xl, m.t + ph + 4, o) + sketchLine(sd + 61, xr, m.t - 4, xr, m.t + ph + 4, o)} fill="none" stroke={inkColor} strokeWidth={strokeWidth} strokeLinecap="round" {...draw(axisP)} />

        {rows.map((r, i) => {
          const ip = ease(clamp((p - 0.15 - (i / Math.max(1, n)) * 0.45) / 0.38, 0, 1))
          const y = m.t + i * band + (band - bh) / 2
          const LA = len(valA(r))
          const LB = len(valB(r))
          const la = LA * ip
          const lb = LB * ip
          const on = hov < 0 || hov === i
          const sw = hov === i ? strokeWidth * 1.5 : strokeWidth
          const lp = ease(clamp((ip - 0.8) / 0.2, 0, 1))
          return (
            <g key={i} opacity={on ? 1 : 0.35} style={{ transition: 'opacity .2s' }}
              onMouseEnter={(e) => { setHov(i); tooltip && setTip(tipAt(e, wrap, r.label, [{ color: leftColor, label: leftLabel, value: fmt(valA(r)) }, { color: rightColor, label: rightLabel, value: fmt(valB(r)) }, { label: `${rightLabel} − ${leftLabel}`, value: `${valB(r) - valA(r) >= 0 ? '+' : '−'}${fmt(Math.abs(valB(r) - valA(r)))}` }])) }}
              onMouseMove={(e) => tooltip && setTip((tp) => (tp ? { ...tp, ...tipAt(e, wrap, tp.title, tp.rows) } : tp))}
            >
              <rect x={0} y={m.t + i * band} width={W} height={band} fill="transparent" />
              {la > 0.5 && (
                <>
                  <SketchFill id={`${uid}l${i}`} clip={`M${xl - la},${y}h${la}v${bh}h${-la}Z`} box={{ x: xl - LA, y, w: LA, h: bh }} color={leftColor} o={o} seed={sd + i * 7} angle={angL} />
                  <path d={sketchRect(sd + i * 5, xl - la, y, la, bh, { ...o, roughness: roughness * 0.7 })} fill="none" stroke={inkColor} strokeWidth={sw} strokeLinejoin="round" strokeLinecap="round" />
                </>
              )}
              {lb > 0.5 && (
                <>
                  <SketchFill id={`${uid}r${i}`} clip={`M${xr},${y}h${lb}v${bh}h${-lb}Z`} box={{ x: xr, y, w: LB, h: bh }} color={rightColor} o={o} seed={sd + i * 7 + 3} angle={angR} />
                  <path d={sketchRect(sd + i * 5 + 2, xr, y, lb, bh, { ...o, roughness: roughness * 0.7 })} fill="none" stroke={inkColor} strokeWidth={sw} strokeLinejoin="round" strokeLinecap="round" />
                </>
              )}
              {showValues && lp > 0 && (
                <g opacity={lp} style={{ pointerEvents: 'none' }}>
                  <text x={xl - la - 6} y={y + bh / 2} dy="0.34em" textAnchor="end" fontSize={size * 0.88} fontWeight={hov === i ? 700 : 400} fill={hov === i ? leftColor : mutedInk}>{fmt(valA(r))}</text>
                  <text x={xr + lb + 6} y={y + bh / 2} dy="0.34em" fontSize={size * 0.88} fontWeight={hov === i ? 700 : 400} fill={hov === i ? rightColor : mutedInk}>{fmt(valB(r))}</text>
                </g>
              )}
              {hov === i && centerLabels && <path d={sketchLine(sd + 90 + i, cx - mid / 2 + 8, y + bh * 0.62, cx + mid / 2 - 8, y + bh * 0.56, { ...o, doubleStroke: false, roughness: roughness * 0.4 })} fill="none" stroke="#f2c94c" strokeOpacity="0.6" strokeWidth={Math.min(bh * 0.55, size * 0.75)} strokeLinecap="round" style={{ pointerEvents: 'none' }} />}
              <text x={centerLabels ? cx : m.l - 10} y={y + bh / 2} dy="0.34em" textAnchor={centerLabels ? 'middle' : 'end'} fontSize={size * 0.98} fontWeight={hov === i ? 700 : 400} fill={hov === i ? inkColor : mutedInk} opacity={axisP} style={{ pointerEvents: 'none' }}>{r.label}</text>
            </g>
          )
        })}
      </svg>
    </Paper>
  )
}
