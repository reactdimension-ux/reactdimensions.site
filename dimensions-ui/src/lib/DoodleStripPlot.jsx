// Doodle strip / swarm plot: every data point is a tiny single-stroke pen circle, scattered
// sideways (`strip`) or packed into a beeswarm (`swarm`). A pencil-ruled, lightly hatched
// band marks the middle 50%, and a thick marker bar crosses each group at its median. Hover
// near a point for its value. Paste raw samples into `data` or leave it empty for the demo
// set (groups, samples, seed, spread). `inkSeed` sets the wobble.

// one cheap pen loop: two arcs that go round a little more than once
function penDot(r, cx, cy, rad, rough) {
  const a0 = r() * Math.PI * 2
  const k1 = 1 + (r() - 0.5) * 0.18 * rough
  const k2 = 1 + (r() - 0.3) * 0.22 * rough
  const at = (a, k) => `${f1(cx + Math.cos(a) * rad * k)},${f1(cy + Math.sin(a) * rad * k)}`
  return `M${at(a0, 1)}A${f1(rad * k1)},${f1(rad * k1)} 0 0 1 ${at(a0 + Math.PI, k1)}A${f1(rad * k2)},${f1(rad * k2)} 0 1 1 ${at(a0 + Math.PI * 2 + 0.45, k2)}`
}

export default function DoodleStripPlot({
  data = '',
  groups = 4,
  samples = 70,
  seed = 3,
  spread = 1,
  names = '',
  title = 'Every measurement',
  subtitle = 'One dot per request, grouped by region',
  mode = 'swarm',
  orientation = 'vertical',
  pointSize = 4.2,
  pointOpacity = 0.85,
  jitter = 0.7,
  colorMode = 'group',
  showBand = true,
  showMedian = true,
  showMean = false,
  showGrid = true,
  showAxis = true,
  tooltip = true,
  roughness = 1.2,
  bowing = 1,
  fillStyle = 'hachure',
  hachureGap = 6,
  hachureAngle = -41,
  strokeWidth = 1.8,
  doubleStroke = true,
  boil = false,
  drawOn = true,
  duration = 2000,
  inkSeed = 25,
  decimals = 0,
  prefix = '',
  suffix = ' ms',
  paper = 'grid',
  tilt = -0.6,
  width = 680,
  height = 300,
  size = 15,
  font = HAND,
  color = '#e4572e',
  color2 = '#2e86ab',
  color3 = '#3bb273',
  color4 = '#9b5de5',
  paperColor = '#fbf8f1',
  inkColor = '#2b2b2b',
  mutedInk = '#77736b',
}) {
  const uid = useId().replace(/:/g, '')
  const wrap = useRef(null)
  const [boxRef, boxW] = useWidth()
  const t = useBoil(boil)
  const sd = inkSeed * 53 + t * 13
  const o = { roughness, bowing, fillStyle, hachureGap, hachureAngle, strokeWidth, doubleStroke }
  const pal = [color, color2, color3, color4]
  const fmt = makeFmt({ decimals, prefix, suffix })
  const G = useSamples({ data, groups, samples, seed, spread, names })
  const S = useMemo(() => G.map((g) => summarize(g.values)), [G])
  const p = useReveal(drawOn, duration, `${data}|${groups}|${samples}|${seed}|${spread}|${mode}|${orientation}|${jitter}`)
  const [hov, setHov] = useState(null) // { g, k }
  const [tip, setTip] = useState(null)

  const horizontal = orientation === 'horizontal'
  const n = G.length
  const lo0 = Math.min(...S.map((s) => s.min))
  const hi0 = Math.max(...S.map((s) => s.max))
  const pad = (hi0 - lo0) * 0.05
  const sc = niceRange(lo0 - pad, hi0 + pad, 5)
  const ticks = ticksOf(sc)
  const tl = ticks.map((v) => prefix + fmtTick(v) + suffix)

  const W = Math.max(260, (boxW || width) - size * 2.8)
  const H = height
  const maxLab = Math.min(16, Math.max(1, ...G.map((g) => g.label.length)))
  const m = horizontal
    ? { l: maxLab * size * 0.5 + 16, r: 14, t: 8, b: showAxis ? size * 2 : 8 }
    : { l: showAxis ? Math.max(...tl.map((s) => s.length)) * size * 0.5 + 16 : 8, r: 10, t: 12, b: size * 2.1 }
  const pw = Math.max(40, W - m.l - m.r)
  const ph = Math.max(40, H - m.t - m.b)
  const band = (horizontal ? ph : pw) / Math.max(1, n)
  const span = horizontal ? pw : ph
  const along = (v) => (span * (v - sc.lo)) / (sc.hi - sc.lo)
  const r0 = pointSize

  // offset of every point across its band (same packing as the Strip Plot)
  const layout = useMemo(
    () =>
      G.map((g, gi) => {
        const rnd = rng(gi * 53 + 9)
        const limit = band * 0.46
        const order = g.values.map((v, k) => k).sort((a, b) => g.values[a] - g.values[b])
        const off = new Array(g.values.length).fill(0)
        if (mode === 'strip') {
          g.values.forEach((_, k) => (off[k] = (rnd() - 0.5) * 2 * limit * clamp(jitter, 0, 1)))
        } else {
          const placed = []
          for (const k of order) {
            const u = along(g.values[k])
            let best = 0
            for (let step = 0; step < 400; step++) {
              const cand = step === 0 ? 0 : (step % 2 ? 1 : -1) * Math.ceil(step / 2) * r0 * 0.55
              if (Math.abs(cand) > limit) {
                best = clamp(cand, -limit, limit)
                break
              }
              let ok = true
              for (let q = placed.length - 1; q >= 0; q--) {
                const d = u - placed[q].u
                if (d > r0 * 2.1) break
                if (Math.hypot(d, cand - placed[q].o) < r0 * 2.05) {
                  ok = false
                  break
                }
              }
              if (ok) {
                best = cand
                break
              }
            }
            off[k] = best
            placed.push({ u, o: best })
          }
        }
        const rank = new Array(g.values.length)
        order.forEach((k, i) => (rank[k] = i))
        return { off, order, rank }
      }),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [G, mode, jitter, band, span, sc.lo, sc.hi, r0],
  )

  const P = (v, gi, off = 0) => {
    const mid = (horizontal ? m.t : m.l) + gi * band + band / 2 + off
    return horizontal ? [m.l + along(v), mid] : [mid, m.t + ph - along(v)]
  }
  const colorFor = (gi, v) => (colorMode === 'value' ? mix(color2, color, (v - lo0) / (hi0 - lo0 || 1)) : pal[gi % 4])
  const dimG = (gi) => (hov && hov.g !== gi ? 0.25 : 1)
  const axisP = ease(clamp(p / 0.22, 0, 1))
  const draw = (k) => ({ pathLength: 1, strokeDasharray: 1, strokeDashoffset: 1 - k })
  const thin = { ...o, doubleStroke: false, roughness: roughness * 0.5 }
  const ipG = ease(clamp((p - 0.15) / 0.4, 0, 1))
  const late = ease(clamp((p - 0.65) / 0.3, 0, 1))

  // all point positions, for drawing and for nearest-point hover
  const pts = G.flatMap((g, gi) => g.values.map((v, k) => { const [x, y] = P(v, gi, layout[gi].off[k]); return { gi, k, v, x, y } }))
  const onMove = (e) => {
    const svg = e.currentTarget.ownerSVGElement
    const b = svg.getBoundingClientRect()
    const mx = ((e.clientX - b.left) / b.width) * W
    const my = ((e.clientY - b.top) / b.height) * H
    let best = null
    let bd = Math.max(r0 * 2.2, 10) ** 2
    for (const q of pts) {
      const d = (q.x - mx) ** 2 + (q.y - my) ** 2
      if (d < bd) {
        bd = d
        best = q
      }
    }
    if (!best) {
      setHov(null)
      setTip(null)
      return
    }
    setHov({ g: best.gi, k: best.k })
    if (tooltip) setTip(tipAt(e, wrap, G[best.gi].label, [{ color: colorFor(best.gi, best.v), label: 'Value', value: fmt(best.v) }, { label: 'Median', value: fmt(S[best.gi].med) }]))
  }

  return (
    <Paper wrapRef={(el) => { wrap.current = el; boxRef.current = el }} {...{ width, paper, paperColor, inkColor, mutedInk, size, font, tilt, title, subtitle, tip, accent: color4 }}>
      <svg
        width={W}
        height={H}
        viewBox={`0 0 ${W} ${H}`}
        role="img"
        aria-label={`${title}. Hand-drawn ${mode === 'swarm' ? 'swarm' : 'strip'} plot. ${G.map((g, i) => `${g.label}: ${g.values.length} points, median ${fmt(S[i].med)}`).join('; ')}`}
        style={{ display: 'block', maxWidth: '100%', overflow: 'visible' }}
        onMouseLeave={() => { setHov(null); setTip(null) }}
      >
        {ticks.map((v, i) => {
          const g = horizontal ? m.l + along(v) : m.t + ph - along(v)
          return (
            <g key={i}>
              {showGrid && <path d={horizontal ? sketchLine(sd + i, g, m.t + 4, g, m.t + ph - 4, thin) : sketchLine(sd + i, m.l + 6, g, m.l + pw, g, thin)} fill="none" stroke={inkColor} strokeOpacity="0.15" strokeWidth="1" {...draw(axisP)} />}
              {showAxis && <text x={horizontal ? g : m.l - 10} y={horizontal ? m.t + ph + size * 1.35 : g} dy={horizontal ? 0 : '0.34em'} textAnchor={horizontal ? 'middle' : 'end'} fontSize={size * 0.9} fill={mutedInk} opacity={axisP}>{tl[i]}</text>}
            </g>
          )
        })}
        {showAxis && <path d={sketchLine(sd + 60, m.l - 4, m.t + ph, m.l + pw + 4, m.t + ph, o) + sketchLine(sd + 61, m.l, m.t - 4, m.l, m.t + ph + 2, o)} fill="none" stroke={inkColor} strokeWidth={strokeWidth} strokeLinecap="round" {...draw(axisP)} />}

        {G.map((g, gi) => {
          const s = S[gi]
          const c = pal[gi % 4]
          const pen = mix(c, inkColor, 0.3)
          const half = band * 0.46
          const [a1, a2] = [P(s.q1, gi, -half), P(s.q3, gi, half)]
          const bx = { x: Math.min(a1[0], a2[0]), y: Math.min(a1[1], a2[1]), w: Math.abs(a2[0] - a1[0]), h: Math.abs(a2[1] - a1[1]) }
          const mk = (v, w = half) => [...P(v, gi, -w), ...P(v, gi, w)]
          const lab = g.label.length > 16 ? g.label.slice(0, 15) + '…' : g.label
          const [lx, ly] = horizontal ? [m.l - 10, m.t + gi * band + band / 2] : [m.l + gi * band + band / 2, m.t + ph + size * 1.4]
          const hotG = hov && hov.g === gi
          return (
            <g key={gi} opacity={dimG(gi)} style={{ transition: 'opacity .2s' }}>
              {showBand && (
                <g opacity={ipG}>
                  <SketchFill id={`${uid}s${gi}`} clip={`M${bx.x},${bx.y}h${bx.w}v${bx.h}h${-bx.w}Z`} box={bx} color={c} o={{ ...o, hachureGap: hachureGap * 1.6 }} seed={sd + gi * 13} angle={hachureAngle + gi * 30} opacity={0.2} />
                  <path d={sketchRect(sd + gi * 7, bx.x, bx.y, bx.w, bx.h, { ...o, doubleStroke: false, roughness: roughness * 0.6 })} fill="none" stroke={c} strokeOpacity="0.45" strokeWidth="1.1" strokeLinejoin="round" />
                </g>
              )}
              {g.values.map((v, k) => {
                const ip = ease(clamp((p - 0.1 - (layout[gi].rank[k] / g.values.length) * 0.5) / 0.4, 0, 1))
                if (ip <= 0) return null
                const [px, py] = P(v, gi, layout[gi].off[k])
                const active = hotG && hov.k === k
                const col = colorFor(gi, v)
                return (
                  <path
                    key={k}
                    d={penDot(srng(sd + gi * 1009 + k), px, py, (active ? r0 * 1.6 : r0) * ip, roughness)}
                    fill={col}
                    fillOpacity={pointOpacity * 0.3}
                    stroke={active ? inkColor : col}
                    strokeOpacity={active ? 1 : pointOpacity}
                    strokeWidth={active ? strokeWidth * 0.9 : Math.max(1, strokeWidth * 0.6)}
                    strokeLinecap="round"
                    style={{ pointerEvents: 'none' }}
                  />
                )
              })}
              {showMean && <path d={sketchLine(sd + 200 + gi, ...mk(s.mean, half * 0.7), { ...o, doubleStroke: false })} fill="none" stroke={pen} strokeWidth={strokeWidth * 1.1} strokeDasharray="5 4" strokeLinecap="round" opacity={late} style={{ pointerEvents: 'none' }} />}
              {showMedian && <path d={sketchLine(sd + 220 + gi, ...mk(s.med), { ...o, roughness: roughness * 0.6 })} fill="none" stroke={inkColor} strokeWidth={strokeWidth * 1.5} strokeLinecap="round" style={{ pointerEvents: 'none' }} {...draw(late)} />}
              <text x={lx} y={ly} dy={horizontal ? '0.34em' : 0} textAnchor={horizontal ? 'end' : 'middle'} fontSize={size * 1.02} fill={hotG ? inkColor : mutedInk} fontWeight={hotG ? 700 : 400} style={{ transition: 'fill .2s' }}>{lab}</text>
            </g>
          )
        })}
        <rect x={m.l} y={m.t} width={pw} height={ph} fill="transparent" onMouseMove={onMove} />
      </svg>
    </Paper>
  )
}
